import { createHash } from 'node:crypto'
import { fileURLToPath } from 'node:url'
import { ImageError } from './provider.js'
import { assetKind } from './assets.js'

export async function writerPlan(ctx, root, exec, kind = 'image') {
  assetKind(kind)
  const policy = ctx.sandboxPolicy.resolve({ session: exec.agent.session })
  return await ctx.sandbox.confine([process.execPath, fileURLToPath(new URL('./writer.js', import.meta.url)), kind], {
    ...policy, mode: 'workspace-write', workspaceRoot: root,
  })
}

export function writerEnvironment(runtime = process) {
  // Tombstones clear ordinary parent entries too: no launch credentials or
  // NODE_OPTIONS enter the asset writer, even if the host inherited them.
  const env = Object.fromEntries(Object.keys(runtime.env).map(key => [key, undefined]))
  if (runtime.platform === 'win32') env.SystemRoot = runtime.env.SystemRoot
  // Desktop's macOS Host is an Electron utility process. Its executable runs
  // this child script only in Node mode; this constant is launch configuration.
  if (runtime.versions.electron) env.ELECTRON_RUN_AS_NODE = '1'
  return env
}

export async function commitImage(ctx, root, data, exec) {
  return commitAsset(ctx, root, data, exec, 'image')
}

/** Save generated bytes through the sandboxed writer and check the asset identity it reports. */
export async function commitAsset(ctx, root, data, exec, kind) {
  const { folder, extension } = assetKind(kind)
  const plan = await writerPlan(ctx, root, exec, kind)
  // A video travels to the writer as base64 on stdin; give it time to stream.
  const signal = AbortSignal.any([AbortSignal.timeout(kind === 'video' ? 180_000 : 30_000), ...(exec.signal ? [exec.signal] : [])])
  const child = ctx.subprocess.spawn({
    argv: plan.argv, cwd: root, env: writerEnvironment(), signal, graceMs: 1000,
    stdio: { stdin: { data: data.toString('base64') }, stdout: { maxBytes: 1024 }, stderr: { maxBytes: 2048 } },
  })
  const outcome = await child.done
  signal.throwIfAborted()
  if (outcome.exitCode !== 0) throw new ImageError('ASSET_PATH', 'The sandbox could not save the generated file. Check workspace permissions and sandbox availability.')
  let result
  try { result = JSON.parse(child.collected.stdout.readFrom(0).text) } catch { throw new ImageError('ASSET_PATH', 'The asset writer returned an invalid result.') }
  const hash = createHash('sha256').update(data).digest('hex')
  if (result.sha256 !== hash || result.workspace_path !== `.workbuddy/${folder}/${hash}.${extension}`) throw new ImageError('ASSET_PATH', 'The generated asset identity does not match its content.')
  return result
}
